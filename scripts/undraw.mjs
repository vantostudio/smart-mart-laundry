// Turns unDraw illustrations (https://undraw.co, free licence, no attribution needed) into React
// components coloured with our design tokens, written to src/components/illustrations/.
//
// usage:  node scripts/undraw.mjs <ComponentName>=<cdn path> …
// e.g.    node scripts/undraw.mjs Booked=illustrations/booked_bb22
//
// Colours are mapped to Tailwind fill utilities, so the art follows the theme (and turns light on
// surface-inverse bands). Unknown colours fail loudly — add them to the map.
import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const fills = {
  "#6c63ff": "fill-clay", // unDraw's accent → our call-to-action colour
  "#090814": "fill-foreground",
  "#2f2e41": "fill-foreground",
  "#3f3d56": "fill-foreground",
  "#fff": "fill-card",
  "#ffffff": "fill-card",
  "#f2f2f2": "fill-muted",
  "#e6e6e6": "fill-muted",
  "#d6d6e3": "fill-border",
  "#ccc": "fill-border",
  "#b3b3b3": "fill-border",
  "#ed9da0": "fill-skin", // skin tones → a warm brown that fits our customers
  "#ffb8b8": "fill-skin",
  "#ffb6b6": "fill-skin",
};

const outDir = "src/components/illustrations";
mkdirSync(outDir, { recursive: true });

for (const arg of process.argv.slice(2)) {
  const [name, path] = arg.split("=");
  const res = await fetch(`https://cdn.undraw.co/${path}.svg`);
  if (!res.ok) throw new Error(`${path}: HTTP ${res.status}`);
  let svg = await res.text();

  const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1];
  const body = svg
    .replace(/^[\s\S]*?<svg[^>]*>/, "")
    .replace(/<\/svg>\s*$/, "")
    .replace(/ (id|data-name)="[^"]*"/g, "")
    .replace(/ fill="(#[0-9a-fA-F]{3,6})"/g, (_, hex) => {
      const cls = fills[hex.toLowerCase()];
      if (!cls) throw new Error(`${path}: no token for ${hex}`);
      return ` className="${cls}"`;
    });

  writeFileSync(
    join(outDir, `${name.replace(/[A-Z]/g, (c, i) => (i ? "-" : "") + c.toLowerCase())}.tsx`),
    `// Generated by scripts/undraw.mjs from unDraw "${path}". Do not edit by hand.
import type { SVGProps } from "react";

import { cn } from "@/lib/utils";

export function ${name}Illustration({ className, ...props }: SVGProps<SVGSVGElement>) {
  return (
    <svg viewBox="${viewBox}" aria-hidden className={cn("fill-foreground", className)} {...props}>
      ${body}
    </svg>
  );
}
`,
  );
  console.log(`${name} ← ${path}`);
}
